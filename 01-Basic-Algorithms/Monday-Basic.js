// ============================================================
// 1. Print 1 - 135
// ============================================================
/* T-Diagram:
   Iteration | i   | Output
   ----------|-----|-------
   1         | 1   | 1
   2         | 2   | 2
   ...       | ... | ...
   135       | 135 | 135
*/
for (let i = 1; i <= 135; i++) {
    console.log(i);
}

// ============================================================
// 2. Print Odd Numbers 1 - 135
// ============================================================
/* T-Diagram:
   Iteration | i   | i % 2 !== 0 | Output
   ----------|-----|-------------|-------
   1         | 1   | true        | 1
   2         | 2   | false       | -
   3         | 3   | true        | 3
*/
for (let i = 1; i <= 135; i++) {
    if (i % 2 !== 0) {
        console.log(i);
    }
}

// ============================================================
// 3. Sum of Printed Numbers
// ============================================================
/* T-Diagram:
   Iteration | i   | sum (before) | sum (after) | Output
   ----------|-----|--------------|-------------|-------
   1         | 0   | 0            | 0           | Number is: 0 Sum: 0
   2         | 1   | 0            | 1           | Number is: 1 Sum: 1
   3         | 2   | 1            | 3           | Number is: 2 Sum: 3
*/
let sum = 0;
for (let i = 0; i <= 135; i++) {
    sum += i;
    console.log("Number is: " + i + " Sum: " + sum);
}

// ============================================================
// 4. Print the elements of an array
// ============================================================
/* T-Diagram (X = [1,4,2,12]):
   Iteration | i   | X[i]  | Output
   ----------|-----|-------|-------
   1         | 0   | 1     | 1
   2         | 1   | 4     | 4
   ...       | ... | ...   | ...
*/
let X4 = [1, 4, 2, 12];
for (let i = 0; i < X4.length; i++) {
    console.log(X4[i]);
}

// ============================================================
// 5. Find Max
// ============================================================
/* T-Diagram (X = [2,-3,-1]):
   Iteration | i   | max (current) | X[i] | New Max? | max (after)
   ----------|-----|---------------|------|----------|-----------
   1         | 0   | 2 (initial)   | 2    | No       | 2
   2         | 1   | 2             | -3   | No       | 2
   3         | 2   | 2             | -1   | No       | 2
*/
let X5 = [2, -3, -1];
let max = X5[0];
for (let i = 1; i < X5.length; i++) {
    if (X5[i] > max) {
        max = X5[i];
    }
}
console.log("Max is: " + max);

// ============================================================
// 6. Get Average
// ============================================================
/* T-Diagram (X = [2,1,3]):
   Iteration | i   | sum | Output (sum / length)
   ----------|-----|-----|-------
   1         | 0   | 2   | -
   2         | 1   | 3   | -
   3         | 2   | 6   | 2 (6 / 3)
*/
let X6 = [2, 1, 3];
let totalSum = 0;
for (let i = 0; i < X6.length; i++) {
    totalSum += X6[i];
}
console.log("Average is: " + totalSum / X6.length);

// ============================================================
// 7. Eliminate the Negatives
// ============================================================
/* T-Diagram (X = [2,-1,4,-3]):
   Iteration | i   | X[i] | Condition (X[i] < 0) | X (after)
   ----------|-----|------|----------------------|----------
   1         | 0   | 2    | false                | [2,-1,4,-3]
   2         | 1   | -1   | true                 | [2,0,4,-3]
   ...       | ... | ...  | ...                  | [2,0,4,0]
*/
let X7 = [2, -1, 4, -3];
for (let i = 0; i < X7.length; i++) {
    if (X7[i] < 0) {
        X7[i] = 0;
    }
}
console.log(X7);

// ============================================================
// 8. Number to String
// ============================================================
/* T-Diagram (X = [1,-4,0,-1]):
   Iteration | i   | X[i] | Condition (X[i] < 0) | X (after)
   ----------|-----|------|----------------------|----------
   1         | 0   | 1    | false                | [1,-4,0,-1]
   2         | 1   | -4   | true                 | [1,'Turing',0,-1]
*/
let X8 = [1, -4, 0, -1];
for (let i = 0; i < X8.length; i++) {
    if (X8[i] < 0) {
        X8[i] = 'Turing';
    }
}
console.log(X8);